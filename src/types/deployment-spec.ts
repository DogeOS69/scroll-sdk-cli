/**
 * DeploymentSpec - Single source of truth for DogeOS deployments
 *
 * This specification is used by AI agents and deployment scripts to:
 * 1. Generate config.toml
 * 2. Generate doge-config.toml
 * 3. Generate setup_defaults.toml
 * 4. Generate protocol_seed.toml
 * 5. Generate values/*.yaml for Helm charts
 * 6. Validate deployment configurations
 */

export interface DeploymentSpec {
  /** Account and key configuration. Public owner is user-supplied; deployment/activity keys are generated by setup gen-keystore; service signers use setup eth-da-submitter / setup fee-oracle. */
  accounts: AccountsConfig
  /** Explicit per-bootnode public TCP P2P exposure; omitted nodes remain private when supplied. */
  bootnodePublicP2p?: BootnodePublicP2p[]

  /** Bridge configuration */
  bridge: BridgeConfig
  /** Opt-in history read API. Requires explicit history and Activity-enabled Portal images. */
  bridgeHistory?: {enabled: boolean}
  /** Core-managed capacity, prepared locally and installed separately with Helm. */
  capacityManager?: CapacityManagerConfig
  /** Deprecated Celestia DA configuration retained for legacy specs only. */
  celestia?: CelestiaConfig

  /** Contract deployment configuration */
  contracts: ContractsConfig

  /** Database configuration */
  database: DatabaseConfig

  /** Dogecoin L1 configuration */
  dogecoin: DogecoinConfig

  /** Optional standalone dstack controller Helm release; independent of proof identities. */
  dstackController?: DstackControllerConfig

  /** Ethereum DA configuration */
  ethereumDa?: EthereumDaConfig

  /** Explicit fee-oracle write policy. Fresh spec deployments default to live. */
  feeOracle?: {contractWriteMode?: 'dry_run' | 'live'; ethereumRpcUrl?: string}

  /** Frontend and ingress configuration */
  frontend: FrontendConfig

  /** Genesis configuration */
  genesis: GenesisConfig

  /** YAML overlays keyed by generated values filename. Frozen in the plan and reapplied after chart preparation; never place credentials here. */
  helmValues?: Record<string, string>

  /** Explicit identity operations, executed separately by setup gen-keystore. */
  identities?: DeploymentIdentityIntent

  /** Optional container image overrides for services */
  images?: ImagesConfig

  /** Infrastructure configuration */
  infrastructure: InfrastructureConfig

  /** Deployment metadata */
  metadata: DeploymentMetadata

  /** Monitoring intent; credentials remain in private Secret storage. */
  monitoring?: MonitoringConfig

  /** Network and chain configuration */
  network: NetworkConfig

  /** Explicit operations for setup plan/apply. Omission keeps plain generation available. */
  preparation?: PreparationConfig

  /** Proof artifact bucket (doge-config proofArtifacts.s3): coordinator/WP artifact store and the only signer artifact origin. */
  proofArtifacts?: {s3?: {region?: string} & Omit<ArtifactBucketConfig, 'region'>}

  /** Optional proof-coordinator deployment values generation */
  proofCoordinator?: {
    /** Consumer tuning only. Storage coordinates come exclusively from proofArtifacts.s3. */
    artifactStore?: Pick<ProofCoordinatorConfig['artifactStore'], 'maxReadBodyBytes' | 'publicS3EndpointUrl'>
  } & Omit<ProofCoordinatorConfig, 'artifactStore'>

  /**
   * Versioned proof-topology compiler source. Both active profiles may be
   * staged while disabled; changing only `mode` selects the compiled topology.
   */
  proofTopology?: {
    active?: {
      /** Defaults to S3 when proofArtifacts.s3 is configured. */
      artifactStore?: Pick<ProofTopologyArtifactStoreConfig, 'kind' | 'maxReadBodyBytes'>
    } & Omit<ActiveProofTopologySpec, 'artifactStore'>
    /** Artifact prefix is derived from proofArtifacts.s3.keyPrefix. */
    deployment: Omit<ProofTopologyDeploymentConfig, 'artifactKeyPrefix'>
  } & Omit<ProofTopologySpec, 'active' | 'deployment'>

  /** Rollup parameters */
  rollup?: RollupConfig

  /** Bootstrap snapshot bucket (doge-config snapshots.s3), written by the deploy role. */
  snapshots?: {s3?: Omit<ArtifactBucketConfig, 'endpointUrl' | 'forcePathStyle' | 'publicBaseUrl'>}

  /** Optional SDK commit override; plan defaults to --sdk-dir HEAD and freezes the resolved commit. */
  templates?: {sdkRevision?: string}

  /** Optional test/development settings */
  test?: TestConfig

  /** Schema version for forward compatibility */
  version: '1.0'
}

