function sourceImage(valuesDir: string, file: string): string {
  const values = yaml.load(fs.readFileSync(path.join(valuesDir, file), 'utf8')) as {
    image?: {digest?: unknown; repository?: unknown; tag?: unknown}
  }
  const image = values?.image
  if (typeof image?.repository !== 'string' || !/^[\da-z][\d./:_a-z-]*$/.test(image.repository)) {
    throw new Error(`${file}: image.repository must be an explicit container repository`)
  }

  if (image.digest !== undefined && image.digest !== '') {
    if (typeof image.digest !== 'string' || !/^sha256:[\da-f]{64}$/.test(image.digest)) {
      throw new Error(`${file}: image.digest must be a sha256 digest`)
    }

    return `${image.repository}@${image.digest}`
  }

  if (typeof image.tag !== 'string' || !/^\w[\w.-]{0,127}$/.test(image.tag)) {
    throw new Error(`${file}: image.tag or image.digest is required; refusing to keep the package placeholder image`)
  }

  return `${image.repository}:${image.tag}`
}

function composeWithSourceImages(directory: string, valuesDir: string): string {
  const images: Record<string, string> = {
    'l1-interface': sourceImage(valuesDir, 'l1-interface-production.yaml'),
    'l2reth-node': sourceImage(valuesDir, 'l2-reth-rpc-production.yaml'),
  }
  const original = fs.readFileSync(path.join(directory, 'docker-compose.yml'), 'utf8')
  const expected = yaml.load(original) as {services: Record<string, {image: string}>}
  for (const [service, image] of Object.entries(images)) expected.services[service].image = image

  // Preserve package comments, anchors and embedded bootstrap scripts verbatim.
  // This is the block layout used by the self-contained package. Validate the
  // resulting YAML against the exact two-field semantic change before writing.
  let inServices = false
  let service = ''
  const changed = new Set<string>()
  const updated = original.split('\n').map(line => {
    if (/^services:\s*(?:#.*)?$/.test(line)) inServices = true
    else if (/^[^\s#]/.test(line)) inServices = false
    if (!inServices) return line
    const name = /^ {2}["']?([\w-]+)["']?:\s*(?:#.*)?$/.exec(line)
    if (name) service = name[1]
    if (Object.hasOwn(images, service) && /^ {4}image:/.test(line)) {
      changed.add(service)
      return `    image: ${JSON.stringify(images[service])}${line.endsWith('\r') ? '\r' : ''}`
    }

    return line
  }).join('\n')
  if (changed.size !== 2 || !isDeepStrictEqual(yaml.load(updated), expected)) {
    throw new Error('Cannot update Compose images without other changes; expected explicit image fields in the package service blocks')
  }

  return updated
}

export function discoverNetworkNlbDomains(
  values: Record<string, string>, spec?: DeploymentSpec,
  aws: Pick<AwsCliRunner, 'json'> = new AwsCliRunner(),
): Record<string, string[]> {
  // Explicit infrastructure intent selects independent NLBs. A saved values
  // file can predate their activation; it must not suppress metadata reads.
  if (!spec) return discoverExistingNlbDomains(values, undefined, aws)
  return Object.fromEntries(discoverExistingNlb(spec, aws).map(item => [
    `l2-reth-bootnode-${item.entry.index}-p2p`,
    item.publicEndpoints.map(endpoint => endpoint.split(':')[0]),
  ]))
}

function readGeneratedEnv(file: string): Record<string, string> {
  const result: Record<string, string> = {}
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    if (!line || line.startsWith('#')) continue
    const separator = line.indexOf('=')
    if (separator < 1) throw new Error('Invalid generated environment setting')
    result[line.slice(0, separator)] = line.slice(separator + 1)
  }

  return result
}

function envContent(vars: Record<string, string>): string {
  const lines = [
    '# Generated by scrollsdk rpc export-network. Do not edit.',
    '# Operator settings belong in this network directory\'s .env.',
    '# Set DOGEOS_ETHEREUM_RPC_URL there; upstream credentials are not exported.',
  ]
  for (const [key, value] of Object.entries(vars)) {
    if (/access_key|credential|authorization|private_key/i.test(key)) continue
    if (!/^[A-Z][\dA-Z_]*$/.test(key) || /[\0\n\r]/.test(value)) {
      throw new Error(`Invalid generated environment field: ${key}`)
    }

    // Package config is publishable. Do not export credential-bearing URLs,
    // including signed S3 links, even when the setting name is not secret-like.
    for (const match of value.matchAll(/https?:\/\/[^\s"'<>]+/g)) {
      let url: URL
      try { url = new URL(match[0]) } catch { throw new Error(`Invalid URL in ${key}`) }
      if (url.username || url.password || url.search || url.hash) {
        throw new Error(`Credential-bearing or parameterized URL in ${key}; use operator .env settings instead`)
      }
    }

    // Compose dotenv single quotes keep dollar signs and JSON peer lists literal.
    lines.push(`${key}='${value.replaceAll("'", "\\'")}'`)
  }

  return lines.join('\n') + '\n'
}

function validatePublicPeers(value: string): void {
  const peers: unknown = JSON.parse(value)
  if (!Array.isArray(peers) || peers.length === 0) throw new Error('At least one public bootnode peer is required for the network RPC package')
  for (const peer of peers) {
    let valid = false
    try {
      const url = new URL(peer)
      valid = url.protocol === 'enode:' && /^[\da-f]{128}$/i.test(url.username) &&
        !url.password && Boolean(url.hostname) && url.hostname !== 'localhost' &&
        !url.hostname.endsWith('.cluster.local') && Number(url.port) > 0 && Number(url.port) <= 65_535 &&
        !url.pathname && !url.hash && [...url.searchParams.keys()].every(key => key === 'discport')
    } catch { /* Invalid peers are reported without echoing source values. */ }

    if (!valid) throw new Error('Invalid public enode in peer list: expected a 128-hex public key, external host and TCP port; replace placeholders before exporting')
  }
}

export default class RpcExportNetwork extends Command {
  static override description = 'Export chain configuration into the self-contained <network>/config RPC package layout'

  static override examples = [
    '<%= config.bin %> <%= command.id %> -d ~/github/dogeos-rpc-package --doge-config .data/doge-config.toml --values-dir values --namespace default --kube-context YOUR_CONTEXT',
    '# Selects testnet/ or mainnet/ from doge-config.network; exports chain config and both runtime images without starting services.',
  ]

  static override flags = {
    'aws-profile': RpcExport.flags['aws-profile'],
    'doge-config': RpcExport.flags['doge-config'],
    'dogeos-rpc-package-dir': RpcExport.flags['dogeos-rpc-package-dir'],
    'kube-context': Flags.string({description: 'Kubernetes context for Service-owned bootnode discovery; defaults to the current context'}),
    namespace: Flags.string({char: 'n', default: 'default', description: 'Kubernetes namespace for bootnode discovery'}),
    spec: RpcExport.flags.spec,
    'values-dir': RpcExport.flags['values-dir'],
  }

  public override async run(): Promise<void> {
    const {flags} = await this.parse(RpcExportNetwork)
    const {config: dogeConfig} = await loadDogeConfigWithSelection(flags['doge-config'], `${this.config.bin} ${this.id}`)
    const root = path.resolve(flags['dogeos-rpc-package-dir'])
    const exporter = new NetworkConfigExporter([], this.config)
    exporter.validatePackage(root, dogeConfig.network)

    const values = readAlbValues(path.resolve(flags['values-dir']))
    const domains: Record<string, string | string[]> = {}
    const args = flags['kube-context'] ? ['--context', flags['kube-context']] : []
    try {
      const services = JSON.parse(execFileSync('kubectl', [...args, 'get', 'svc', '-n', flags.namespace, '-o', 'json'], {
        encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 10_000,
      }))
      for (const service of services.items) {
        const name = service.metadata?.name
        const ingress = service.status?.loadBalancer?.ingress?.[0]
        if (service.spec?.type === 'LoadBalancer' && /^l2-(?:reth-)?bootnode-\d+-p2p$/.test(name) && ingress) {
          domains[name] = ingress.hostname || ingress.ip
        }
      }
    } catch {
      this.warn('Kubernetes Service discovery unavailable; using independent NLBs or already-public peers from the source configuration.')
    }

    Object.assign(domains, discoverNetworkNlbDomains(values,
      flags.spec ? readExistingAlbSpec(process.cwd(), flags.spec) : undefined, new AwsCliRunner(flags['aws-profile'])))
    const files = exporter.exportNetworkConfig(flags['values-dir'], dogeConfig, root, domains, flags.namespace)
    for (const file of files) this.log(`Generated ${file}`)
    this.log(`Set DOGEOS_ETHEREUM_RPC_URL in ${dogeConfig.network}/.env before starting the package.`)
    this.log('Rollup node and L1 Interface images are copied from source values. Follow the network README for release validation and startup.')
    if (dogeConfig.network === 'mainnet') this.warn('Configuration export does not complete the mainnet release checklist or validate fresh-genesis initialization.')
  }
}

export class NetworkConfigExporter extends RpcExport {
  public exportNetworkConfig(
    valuesDir: string, dogeConfig: DogeConfig, root: string,
    domains: Record<string, string | string[]>, namespace: string,
  ): string[] {
    const {network} = dogeConfig
    const directory = this.validatePackage(root, network)
    // Reuse the proven chain/peer extraction in a private scratch directory.
    // No target files change until chain config and both images have been checked.
    const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'scrollsdk-rpc-network-'))
    try {
      const reth = this.generateL2NodeEnvFiles(undefined, dogeConfig, scratch, domains, namespace, valuesDir)
      if (reth.hasUnresolvedExternalPeers) throw new Error('Unresolved external bootnode peers; provide the correct kube-context and independent NLB --spec before exporting')
      const genesis = this.extractGenesisJson(valuesDir, scratch, network)
      const protocol = this.extractProtocolContextJson(valuesDir, scratch, network)
      const context = JSON.parse(fs.readFileSync(protocol, 'utf8'))
      if (!context || typeof context !== 'object' || Array.isArray(context)) throw new Error('protocolContext must be a JSON object')
      const l1 = this.generateL1InterfaceEnvFile(valuesDir, scratch, network, null)
      const l1Vars = readGeneratedEnv(l1.generatedPath)
      const runtimeNetwork = l1Vars[`${L1}NETWORK_STR`]
      // Released beta.8 uses rust-dogecoin's historical "bitcoin" spelling
      // for Dogecoin mainnet. Preserve the source runtime's accepted spelling.
      if (runtimeNetwork !== network && !(network === 'mainnet' && runtimeNetwork === 'bitcoin')) {
        throw new Error('L1 Interface NETWORK_STR must match doge-config.network')
      }

      if (network === 'mainnet' && Object.keys(l1Vars).some(key => (
        key.startsWith(`${L1}EVENT_PLANE_`) || key.includes('BOOTSTRAP')
      ) && !['', '0', 'false'].includes(l1Vars[key]))) {
        throw new Error('Mainnet configuration contains historical bootstrap settings; resolve the mainnet release inputs instead of copying testnet history')
      }

      Object.assign(l1Vars, {
        [`${L1}API_BIND_ADDRESS`]: '0.0.0.0:8545',
        [`${L1}BEACON_API_LISTEN_ADDRESS`]: '0.0.0.0:5052',
        [`${L1}DATABASE_URL`]: 'sqlite:///data/l1-interface.sqlite',
        [`${L1}GENESIS_JSON_PATH`]: '/app/genesis/genesis.json',
        [`${L1}HEALTH_LISTEN_ADDRESS`]: '0.0.0.0:9090',
        [`${L1}REPLAY_READ__PROTOCOL_CONTEXT_JSON`]: '/app/protocol_context.json',
        [`${L1}REPLAY_READ__SQLITE_PATH`]: '/data/replay.sqlite',
      })
      if (network === 'testnet') l1Vars[`${L1}EVENT_PLANE_ARTIFACT_PATH`] = '/data/l1-interface-historical-artifact.sqlite'
      else delete l1Vars[`${L1}EVENT_PLANE_ARTIFACT_PATH`]

      const rethVars = readGeneratedEnv(reth.l2rethEnvPath)
      rethVars.L2RETH_PEER_LIST = rethVars.L2GETH_PEER_LIST || '[]'
      delete rethVars.L2GETH_PEER_LIST
      delete rethVars.L2RETH_VALID_SIGNER // Current package derives consensus from chain configuration.
      rethVars.L2RETH_L1_ENDPOINT = 'http://l1-interface:8545'
      rethVars.L2RETH_L1_READY_URL = 'http://l1-interface:9090/api/v1/health/ready'
      if (!rethVars.L2RETH_BLOB_S3_URL) throw new Error('The network RPC package requires ethereumDa.blobArchive.s3 in doge-config for L2RETH_BLOB_S3_URL')
      validatePublicPeers(rethVars.L2RETH_PEER_LIST)

      const contents = [fs.readFileSync(genesis, 'utf8'), fs.readFileSync(protocol, 'utf8'), envContent(l1Vars), envContent(rethVars)]
      const compose = composeWithSourceImages(directory, valuesDir)
      const configDirectory = path.join(directory, 'config')
      fs.mkdirSync(configDirectory, {recursive: true})
      const files = OUTPUTS.map((file, index) => {
        const target = path.join(configDirectory, file)
        fs.writeFileSync(target, contents[index])
        return target
      })
      const composePath = path.join(directory, 'docker-compose.yml')
      fs.writeFileSync(composePath, compose)
      return [...files, composePath]
    } finally {
      fs.rmSync(scratch, {force: true, recursive: true})
    }
  }

  public validatePackage(root: string, network: string): string {
    if (!['mainnet', 'testnet'].includes(network)) {
      throw new Error('The self-contained RPC package supports testnet/mainnet directories only; no network is substituted automatically.')
    }

    const directory = path.join(root, network)
    for (const relative of [network, `${network}/docker-compose.yml`, `${network}/config`, ...OUTPUTS.map(file => `${network}/config/${file}`)]) {
      const target = path.join(root, relative)
      if (fs.lstatSync(target, {throwIfNoEntry: false})?.isSymbolicLink()) {
        throw new Error(`Refusing symlink output path: ${target}`)
      }
    }

    for (const file of ['docker-compose.yml', 'env.example', 'scripts/l1-interface_entrypoint.sh', 'scripts/l2reth_entrypoint.sh']) {
      if (!fs.existsSync(path.join(directory, file))) throw new Error(`Missing self-contained package file: ${path.join(directory, file)}. Pass the repository root with -d; use rpc export for the old layout.`)
    }

    const compose = yaml.load(fs.readFileSync(path.join(directory, 'docker-compose.yml'), 'utf8')) as {services?: Record<string, unknown>}
    if (!compose?.services?.['l1-interface'] || !compose.services['l2reth-node']) throw new Error('Expected l1-interface and l2reth-node in the network Compose file')
    return directory
  }
}
