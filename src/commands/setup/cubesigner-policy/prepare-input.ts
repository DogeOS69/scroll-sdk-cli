import * as toml from '@iarna/toml'
import {Command, Flags} from '@oclif/core'
import fs from 'node:fs'
import path from 'node:path'

import {bridgeHash, parseBridgeScript} from '../../../utils/bridge-rotation.js'
import {requirePolicy} from '../../../utils/cubesigner-governance.js'
import {DEFAULT_DEPLOYMENT} from '../../../utils/deployment-paths.js'
import {JsonOutputContext} from '../../../utils/json-output.js'
import {writeJson} from '../../../utils/preparation-io.js'
import {readProofMaterials} from '../../../utils/proof-materials.js'
import {normalizeSignerProofArtifactBaseUrl} from '../../../utils/proof-signer-policy-input.js'
import {proofFileHash, proofRegularFile} from '../../../utils/proof-software-release.js'

export default class PrepareInput extends Command {
  static description = 'Derive the expected-policy input from actual artifacts; external reviewed identity digests and real test evidence are required, never synthesized'
  static flags = {
    'build-receipt': Flags.string({default: '.data/cubesigner-policy/build-receipt.json'}),
    dir: Flags.string({default: DEFAULT_DEPLOYMENT}),
    environment: Flags.string({options: ['beta', 'gamma', 'prod'], required: true}),
    json: Flags.boolean({default: false}),
    'live-evidence': Flags.string({description: 'Reviewed real acceptance report, if already available; never generated by this command'}),
    materials: Flags.string({default: '.data/proof-materials-v1.json'}),
    organization: Flags.string({required: true}),
    output: Flags.string({default: '.scrollsdk/inputs/cubesigner-policy/preparation.json'}),
    policy: Flags.string({description: 'Published concrete name/vN, v1 or later', required: true}),
    'program-identity-digest': Flags.string({description: 'Reviewed release program identity digest; not the VM executable file hash', required: true}),
    'requires-live-evidence': Flags.boolean({allowNo: true, description: 'Selected release requirement; disabling a required check is not a canary workaround', required: true}),
    'resolver-base-url': Flags.string({description: 'Exact compiled proof artifact root, including path', required: true}),
    tests: Flags.string({description: 'Actual reviewed test report with result, source/Wasm/context and compiled bindings', required: true}),
    'verifier-identity-digest': Flags.string({required: true}),
    wasm: Flags.string({default: '.data/cubesigner-policy/cubesigner_verifier_policy.wasm'}),
  }

  async run(): Promise<void> {
    const {flags} = await this.parse(PrepareInput)
    const output = new JsonOutputContext('setup cubesigner-policy prepare-input', flags.json)
    try {
      requirePolicy(/^[\da-z][\d._a-z-]{2,63}\/v[1-9]\d{0,8}$/.test(flags.policy), 'Select a concrete published name/vN, v1 or later')
      requirePolicy([flags['program-identity-digest'], flags['verifier-identity-digest']].every(value => /^sha256:[\da-f]{64}$/.test(value)), 'Reviewed SHA-256 identity digests required')
      const root = fs.realpathSync(flags.dir)
      const ref = (relative: string) => ({path: relative, sha256: `sha256:${proofFileHash(proofRegularFile(path.resolve(root, relative)))}`})
      const read = (relative: string) => JSON.parse(fs.readFileSync(proofRegularFile(path.resolve(root, relative)), 'utf8'))
      const config = toml.parse(fs.readFileSync(path.join(root, '.data/doge-config.toml'), 'utf8')) as any
      requirePolicy(config.cubesigner?.roles?.length === 1 && config.cubesigner.roles[0].keys.length === 1, 'Select one existing key and role')
      const role = config.cubesigner.roles[0]
      const key = role.keys[0]
      const materials = readProofMaterials(path.resolve(root, flags.materials), root)
      requirePolicy(materials.bridge && materials.software.artifacts, 'Full real materials required')
      const bridge = read('.data/bridge.json')
      const parsed = parseBridgeScript(bridge.redeem_script_hex)
      const base = normalizeSignerProofArtifactBaseUrl(flags['resolver-base-url'])
      requirePolicy(new URL(base).protocol === 'https:', 'Production resolver must be HTTPS')
      const build = read(flags['build-receipt'])
      const input = {aggregateVerifyingKey: ref(materials.software.artifacts.aggregateVerifyingKey.path), bridgeProgram: ref(materials.bridge.artifacts.appExe.path),
        buildReceipt: ref(flags['build-receipt']), environment: flags.environment,
        key: {keyId: key.key_id, materialId: key.material_id, roleId: role.role_id}, materials: ref(flags.materials),
        organization: flags.organization, publicBridge: ref('.data/bridge.json'),
        release: {bindings: {aggregateVkIdentity: materials.bridge.identity.verificationKeyHash, bridgeKeyHash: bridgeHash(bridge.redeem_script_hex), bridgeProgramCommitment: materials.bridge.identity.programCommitmentHash, namespaceId: parsed.namespace,
            proofArtifactBaseUrl: base, teePublicKey: parsed.tee}, coreRevision: build.coreRevision, policyIdentifier: flags.policy, programIdentityDigest: flags['program-identity-digest'],
          proofResolverAuthority: new URL(base).origin, protocolContextSha256: ref('.data/protocol_context.json').sha256,
          requestContract: 'dogeos-cubesigner-compact-psbt-bridge-proof-ref-v1-sign-all-scripts-false-unprefixed-hex-explain-v3', requiresLiveEvidence: flags['requires-live-evidence'],
          sdkVersion: '0.4.281', tests: {...ref(flags.tests), result: read(flags.tests).result},
          verifierIdentityDigest: flags['verifier-identity-digest'],
          verifierProvenance: {aggregateVerifyingKeySha256: ref(materials.software.artifacts.aggregateVerifyingKey.path).sha256, bridgeProgramSha256: ref(materials.bridge.artifacts.appExe.path).sha256},
          wasm: {...ref(flags.wasm), sizeBytes: fs.statSync(path.resolve(root, flags.wasm)).size}}}
      requirePolicy(!fs.existsSync(path.resolve(root, flags.output)), 'Preparation input exists; select a new output for reviewed changes')
      writeJson(path.resolve(root, flags.output), input)
      output.success({file: flags.output, nextCommand: `scrollsdk setup cubesigner-policy prepare --dir . --input ${flags.output}`, status: 'input-derived-not-verified'})
    } catch {output.error('E747_POLICY_INPUT_INVALID', 'Cannot derive policy inputs; check real materials, reviewed source/build, published version and test evidence. No test result was manufactured.', 'VALIDATION', true)}
  }
}
