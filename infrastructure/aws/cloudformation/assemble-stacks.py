#!/usr/bin/env python3
"""Build reviewable lifecycle stacks offline. No AWS calls or environment secrets.

Components remain the source of truth. Stable prefixes become CloudFormation logical
IDs: changing a prefix on an existing stack is a resource replacement, not a rename.
"""
import argparse
import copy
import json
from pathlib import Path
import re
import yaml

ROOT = Path(__file__).resolve().parent
def multiline(dumper, value):
    return dumper.represent_scalar('tag:yaml.org,2002:str', value, style='|' if '\n' in value else None)


yaml.SafeDumper.add_representer(str, multiline)

SHARED = {'Environment', 'ResourceClassification'}
RECIPES = {
    'signing-identities': [(purpose, 'signing-key', {}) for purpose in ('EthDa', 'FeeOracle', 'Sequencer0', 'Sequencer1', 'Bridge')],
    'workload-access': [('', 'application-roles', {})],
    'capacity-access': [('', 'dstack-role', {})],
    'public-network': [('Https', 'https-alb', {}), ('Bootnode', 'bootnode-nlb', {'VpcId': {'ref': 'HttpsVpcId'}})],
    'capacity-network': [('Https', 'https-alb', {}), ('Controller', 'http-target', {'ListenerArn': {'output': 'HttpsListenerArn'}, 'VpcId': {'ref': 'HttpsVpcId'}})],
    'secret-metadata': [('', 'proof-secret', {})],
    'cluster-pod-identity': [('', 'pod-identity-agent', {})],
}


def assemble(recipe):
    result = {'AWSTemplateFormatVersion': '2010-09-09',
              'Description': f'DogeOS {recipe} lifecycle stack. Generated by assemble-stacks.py; review before applying.',
              'Parameters': {}, 'Resources': {}, 'Outputs': {}, 'Conditions': {}, 'Rules': {}}
    for prefix, name, bindings in RECIPES[recipe]:
        component = yaml.safe_load((ROOT / f'{name}.yaml').read_text())
        names = {key: key if key in SHARED else prefix + key
                 for section in ('Parameters', 'Resources', 'Outputs', 'Conditions', 'Rules')
                 for key in component.get(section, {})}
        fixed = {}
        for key, value in bindings.items():
            fixed[key] = ({'Ref': value['ref']} if 'ref' in value else copy.deepcopy(result['Outputs'][value['output']]['Value'])) if isinstance(value, dict) else value

        def rewrite(value):
            if isinstance(value, list):
                return [rewrite(item) for item in value]
            if not isinstance(value, dict):
                return value
            if set(value) == {'Ref'}:
                key = value['Ref']
                return copy.deepcopy(fixed[key]) if key in fixed else {'Ref': names.get(key, key)}
            if set(value) == {'Fn::GetAtt'}:
                parts = value['Fn::GetAtt']
                parts = parts.split('.', 1) if isinstance(parts, str) else parts
                return {'Fn::GetAtt': [names.get(parts[0], parts[0]), parts[1]]}
            if set(value) == {'Fn::Sub'}:
                text = value['Fn::Sub']
                if not isinstance(text, str):
                    raise ValueError('Only string Fn::Sub is used by these components')
                # Local variables allow literal/connected parameters in Fn::Sub too.
                used = {key: fixed[key] for key in fixed if '${' + key + '}' in text}
                text = re.sub(r'\$\{([A-Za-z0-9]+)(\.[^}]+)?\}', lambda m: '${' + (m[1] if m[1] in used else names.get(m[1], m[1])) + (m[2] or '') + '}', text)
                return {'Fn::Sub': [text, used] if used else text}
            if set(value) == {'Fn::If'}:
                cond, yes, no = value['Fn::If']
                return {'Fn::If': [names.get(cond, cond), rewrite(yes), rewrite(no)]}
            return {key: names.get(item, item) if key == 'Condition' and isinstance(item, str) else rewrite(item) for key, item in value.items()}

        for section in ('Parameters', 'Resources', 'Outputs', 'Conditions', 'Rules'):
            for key, value in component.get(section, {}).items():
                if section == 'Parameters' and key in fixed:
                    continue
                target = names[key]
                item = rewrite(value)
                if recipe in ('capacity-network', 'public-network') and section == 'Parameters' and key == 'Scheme':
                    scheme = 'internal' if recipe == 'capacity-network' else 'internet-facing'
                    item['Default'] = scheme
                    item['AllowedValues'] = [scheme]
                if section == 'Resources':
                    for tag in item.get('Properties', {}).get('Tags', []):
                        if tag['Key'] == 'Purpose' and prefix:
                            tag['Value'] = prefix
                        if tag['Key'] == 'Name' and prefix:
                            tag['Value'] = {'Fn::Sub': '${Environment}-' + prefix + '-' + key}
                    if name == 'signing-key' and 'Description' in item.get('Properties', {}):
                        item['Properties']['Description'] = {'Fn::Sub': 'DogeOS ${ResourceClassification} ${Environment} ' + prefix + ' signing identity; retain until explicit retirement.'}
                if target in result[section] and result[section][target] != item:
                    raise ValueError(f'Conflicting shared {section}.{target}')
                result[section][target] = item
    return {key: value for key, value in result.items() if value}


def parameters(recipe):
    values = {}
    for prefix, component, bindings in RECIPES[recipe]:
        variant = {'signing-key': 'signing-key.reuse', 'http-target': 'http-target.dstack'}.get(component, component)
        entries = json.loads((ROOT / 'parameters' / (variant + '.example.json')).read_text())
        for entry in entries:
            key, value = entry['ParameterKey'], entry['ParameterValue']
            if key in bindings:
                continue
            if component == 'signing-key' and key == 'AliasName':
                value = 'alias/dogeos/REPLACE_ENV/' + prefix.lower()
            if recipe == 'public-network' and component == 'https-alb':
                if key == 'Scheme': value = 'internet-facing'
                if key == 'PrivateHostname': value = ''
            values[key if key in SHARED else prefix + key] = value
    return [{'ParameterKey': key, 'ParameterValue': value} for key, value in values.items()]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if committed lifecycle templates are stale')
    args = parser.parse_args()
    output = ROOT / 'stacks'
    output.mkdir(exist_ok=True)
    (output / 'parameters').mkdir(exist_ok=True)
    for name in RECIPES:
        rendered = '# Generated by ../assemble-stacks.py. Edit component templates, then regenerate.\n' + yaml.safe_dump(assemble(name), sort_keys=False, width=140)
        artifacts = {output / f'{name}.yaml': rendered, output / 'parameters' / f'{name}.example.json': json.dumps(parameters(name), indent=2) + '\n'}
        for path, content in artifacts.items():
            if args.check:
                if not path.exists() or path.read_text() != content:
                    raise SystemExit(f'Stale lifecycle artifact: {path}')
            else:
                path.write_text(content)


if __name__ == '__main__':
    main()
